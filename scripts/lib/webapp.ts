/**
 * Vite plugin: makes the web build an installable, offline-capable web app
 * ("Add to Home Screen" on iPhone/iPad, "Install app" on Android Chrome), hosted on
 * GitHub Pages under /Cylinder-Protection/ (hence Vite's relative base './').
 *
 * Emits into the build, nothing committed:
 *   manifest.webmanifest, icon-192.png, icon-512.png, icon-maskable-512.png,
 *   apple-touch-icon.png (from the Android icon art, scripts/lib/iconart.ts), and sw.js.
 *
 * The service worker precaches every built file. Page loads are network-first with a
 * 4 s timeout (so a new version shows up on the next launch, and a bad connection
 * falls back to the cached game), everything else is cache-first (Vite's file names
 * are content-hashed). The dev server serves the manifest and icons but no service
 * worker (src/main.ts registers it only in production builds outside Capacitor).
 */
import { createHash } from 'node:crypto';
import type { Plugin } from 'vite';
import { PAGE_BG, maskableIcon, squareIcon } from './iconart';

const NAME = 'Cylinder Protection';
const SHORT = 'Cylinder';

const icons = (): Record<string, Buffer> => ({
  'icon-192.png': squareIcon(192),
  'icon-512.png': squareIcon(512),
  'icon-maskable-512.png': maskableIcon(512),
  'apple-touch-icon.png': squareIcon(180),
});

const manifest = () =>
  JSON.stringify(
    {
      name: NAME,
      short_name: SHORT,
      description: 'A moonlit tower defense: plant elemental blooms and protect the Moonwell from the Blight.',
      id: './',
      start_url: './',
      scope: './',
      display: 'standalone',
      orientation: 'landscape',
      background_color: PAGE_BG,
      theme_color: PAGE_BG,
      icons: [
        { src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
        { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
        { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
      ],
    },
    null,
    2,
  );

const serviceWorker = (version: string, files: string[]) => `// Generated by scripts/lib/webapp.ts
const CACHE = 'cp-${version}';
const PRECACHE = ${JSON.stringify(['./', ...files])};
const INDEX = new URL('./', self.registration.scope).href;

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('cp-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

const timeout = (ms) => new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), ms));

// Page loads: network first so updates arrive, cached index when offline or slow.
async function page(req) {
  const cache = await caches.open(CACHE);
  try {
    const res = await Promise.race([fetch(req), timeout(4000)]);
    if (res.ok) cache.put(INDEX, res.clone());
    return res;
  } catch {
    return (await cache.match(INDEX)) || Response.error();
  }
}

// Everything else: content-hashed, so the cache is always right.
async function asset(req) {
  const hit = await caches.match(req, { ignoreSearch: true });
  if (hit) return hit;
  const res = await fetch(req);
  if (res.ok) {
    const copy = res.clone();
    caches.open(CACHE).then((c) => c.put(req, copy));
  }
  return res;
}

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(req.mode === 'navigate' ? page(req) : asset(req));
});
`;

export function webApp(): Plugin {
  return {
    name: 'cylinder-webapp',
    enforce: 'post', // after Vite's html plugin, so index.html is in the bundle
    configureServer(server) {
      const files: Record<string, Buffer> = { ...icons(), 'manifest.webmanifest': Buffer.from(manifest()) };
      server.middlewares.use((req, res, next) => {
        const name = (req.url ?? '').split('?')[0].replace(/^\//, '');
        const body = files[name];
        if (!body) return next();
        res.setHeader('Content-Type', name.endsWith('.png') ? 'image/png' : 'application/manifest+json');
        res.end(body);
      });
    },
    generateBundle(_opts, bundle) {
      const own: Record<string, string | Buffer> = { ...icons(), 'manifest.webmanifest': manifest() };
      for (const [fileName, source] of Object.entries(own)) this.emitFile({ type: 'asset', fileName, source });
      // Files emitted here are not in `bundle`'s keys yet: list them explicitly.
      const built = Object.keys(bundle).filter((f) => !f.endsWith('.map'));
      const files = [...new Set([...built, ...Object.keys(own)])].sort();
      // Cache version: every file's name and content, so any change installs a fresh cache.
      const hash = createHash('sha256');
      for (const f of files) {
        const item = bundle[f];
        hash.update(f).update(item ? (item.type === 'chunk' ? item.code : item.source) : own[f]);
      }
      const version = hash.digest('hex').slice(0, 12);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(version, files) });
    },
  };
}
